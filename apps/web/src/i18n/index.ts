export type CopyKey = keyof typeof zh;
export function translate(
  locale: Locale,
  key: CopyKey,
  values: Record<string, string | number> = {},
): string {
  const source = (locale === "zh" ? zh : en)[key];
  return source.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}
